function renderMedia(post) {
  const value = mediaSelections[post.date];
  const items = (Array.isArray(value) ? value : value ? [value] : []).filter((item) => item?.src);
  if (!items.length) return "";
  const className = items.length > 1 ? "daily-media daily-media-gallery" : "daily-media";
  const html = items.map((item) => {
    const display = String(item.capturedAt || "").replace("T", " ").replace(/:\d{2}(?:\.\d+)?(?:Z)?$/, "");
    return `        <div class="daily-media-item">
          <img src="../${escapeHtml(item.src)}" alt="${escapeHtml(item.alt || `${post.date}の記録写真`)}" loading="lazy">
          ${display ? `<figcaption>${escapeHtml(display)}</figcaption>` : ""}
        </div>`;
  }).join("\n");
  return `      <figure class="${className}">
${html}
      </figure>`;
}

function renderSection(section) {
  if (!section || typeof section.heading !== "string") {
    throw new Error("Each Daily Log section needs a heading.");
  }
  const lines = [`      <h2>${escapeHtml(section.heading)}</h2>`];
  for (const paragraph of section.paragraphs || []) {
    lines.push(`      <p>${escapeHtml(paragraph)}</p>`);
  }
  if (Array.isArray(section.bullets) && section.bullets.length) {
    lines.push("      <ul>");
    for (const item of section.bullets) lines.push(`        <li>${escapeHtml(item)}</li>`);
    lines.push("      </ul>");
  }
  return lines.join("\n");
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
